"""Download BTC/USDT 1h candles from the Binance public API (no API key needed).

Raw data is saved unchanged to data/raw/. A metadata JSON records the source,
range and download date.

Run from the ai-service folder:
    python src/download_data.py
"""
import csv
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import requests

SYMBOL = "BTCUSDT"
INTERVAL = "1h"
START = datetime(2020, 1, 1, tzinfo=timezone.utc)
END = datetime(2026, 10, 1, tzinfo=timezone.utc)  # exclusive: last candle = 2026-09-30 23:00
LIMIT = 1000
HOUR_MS = 3_600_000

# Primary endpoint first; the second is Binance's public market-data mirror.
BASE_URLS = ["https://api.binance.com", "https://data-api.binance.vision"]

COLUMNS = [
    "open_time", "open", "high", "low", "close", "volume", "close_time",
    "quote_volume", "trades", "taker_buy_base", "taker_buy_quote", "ignore",
]

RAW_DIR = Path(__file__).resolve().parents[1] / "data" / "raw"


def fetch_page(base_url: str, start_ms: int, end_ms: int) -> list:
    params = {
        "symbol": SYMBOL,
        "interval": INTERVAL,
        "startTime": start_ms,
        "endTime": end_ms,
        "limit": LIMIT,
    }
    for attempt in range(5):
        try:
            r = requests.get(f"{base_url}/api/v3/klines", params=params, timeout=30)
            if r.status_code == 429 or r.status_code == 418:
                wait = int(r.headers.get("Retry-After", 10))
                print(f"Rate limited, waiting {wait}s")
                time.sleep(wait)
                continue
            r.raise_for_status()
            return r.json()
        except requests.RequestException as e:
            print(f"Request error ({e}), retry {attempt + 1}/5")
            time.sleep(2 ** attempt)
    raise RuntimeError("Failed after 5 retries")


def pick_base_url(start_ms: int, end_ms: int) -> str:
    for url in BASE_URLS:
        try:
            fetch_page(url, start_ms, start_ms + HOUR_MS)
            return url
        except Exception as e:  # noqa: BLE001
            print(f"{url} not usable: {e}")
    sys.exit("No Binance endpoint reachable. Check internet / region / firewall.")


def main() -> None:
    start_ms = int(START.timestamp() * 1000)
    end_ms = int(END.timestamp() * 1000) - 1  # inclusive end just before END
    RAW_DIR.mkdir(parents=True, exist_ok=True)

    base_url = pick_base_url(start_ms, end_ms)
    print(f"Using {base_url}")

    rows = []
    cursor = start_ms
    while cursor <= end_ms:
        page = fetch_page(base_url, cursor, end_ms)
        if not page:
            break
        rows.extend(page)
        cursor = page[-1][0] + HOUR_MS
        print(f"{len(rows):>7} candles, up to "
              f"{datetime.fromtimestamp(page[-1][0] / 1000, timezone.utc):%Y-%m-%d %H:%M}")
        time.sleep(0.2)  # be polite to the API

    out_csv = RAW_DIR / f"{SYMBOL}_{INTERVAL}_raw.csv"
    with open(out_csv, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(COLUMNS)
        w.writerows(rows)

    meta = {
        "source": base_url + "/api/v3/klines",
        "symbol": SYMBOL,
        "interval": INTERVAL,
        "requested_start_utc": START.isoformat(),
        "requested_end_exclusive_utc": END.isoformat(),
        "rows_downloaded": len(rows),
        "first_open_time_utc": datetime.fromtimestamp(rows[0][0] / 1000, timezone.utc).isoformat(),
        "last_open_time_utc": datetime.fromtimestamp(rows[-1][0] / 1000, timezone.utc).isoformat(),
        "downloaded_at_utc": datetime.now(timezone.utc).isoformat(),
        "timestamp_unit": "milliseconds, UTC, candle OPEN time",
        "note": "Raw data, unmodified. Do not edit this file.",
    }
    (RAW_DIR / f"{SYMBOL}_{INTERVAL}_raw.meta.json").write_text(json.dumps(meta, indent=2))
    print(f"Saved {len(rows)} rows to {out_csv}")


if __name__ == "__main__":
    main()